% NET14_COLLECT  Table I, Fig. 2, and the numbers quoted in the letter for
% the IEEE 14-bus case, from results/net/i14_*.mat (netrun, cluster) and
% results/net14_params.mat (time per step). Writes results/letter_table14.tex
% and Figure/fig_robust.pdf.
here = fileparts(mfilename('fullpath')); root = fileparts(here);
ld = @(t) getfield(load(fullfile(root, 'results', 'net', ['i14_' t '.mat'])), 'res'); %#ok<GFLD>
pc = @(r, f) 100*r.(f)/r.lb;
Mf = ld('main_free'); Ml = ld('main_lim'); P = load(fullfile(root, 'results', 'net14_params.mat')); ms = P.P.ms;

% ---- Table I: the core benchmarks only (costs in % of the hindsight optimum);
% MPC uses a forecast fitted to past data (netrun method 'mpcfit')
Qf = ld('mpcfit_free'); Ql = ld('mpcfit_lim'); Mf.mpcfit = Qf.mpcfit; Ml.mpcfit = Ql.mpcfit;
on = {'adp', 'ADP \cite{xueContinuousApproximateDynamic2024}', ms.values;
      'cut', 'Tuned cutoffs \cite{rasoolMultiFilterBased2022}', ms.complete;
      'rl', 'RL \cite{shuaiBranchingDuelingQNetwork2021}', ms.track;
      'mpcfit', 'MPC \cite{liMultiStageRealTime2022}', ms.mpc};
[~, o] = sort(cellfun(@(f) pc(Ml, f), on(:,1))); on = [{'prop', '\textbf{Proposed (Alg.~1)}', ms.values}; on(o,:)];
fid = fopen(fullfile(root, 'results', 'letter_table14.tex'), 'w');
fprintf(fid, '%% Generated by net14_collect.m from results/net/i14_*.mat and net14_params.mat.\n');
for k = 1:size(on, 1)
    a = sprintf('%.1f', pc(Mf, on{k,1})); b = sprintf('%.1f', pc(Ml, on{k,1}));
    if k == 1, a = ['\textbf{' a '}']; b = ['\textbf{' b '}']; end
    fprintf(fid, '%s & %s & %s & %.1f \\\\\n', on{k,2}, a, b, on{k,3});
end
ex = @(M, f) (pc(M, f) - pc(M, 'prop'))/(pc(M, f) - 100);    % share of excess cost removed
for k = 2:size(on, 1)
    fprintf('excess cost cut vs %-6s: free %.0f%%, lim %.0f%%\n', on{k,1}, 100*ex(Mf, on{k,1}), 100*ex(Ml, on{k,1}));
end
fprintf('MPC fitted: free %.1f lim %.1f; forecast error 15 min %.2f, 24 h %.2f sigma\n', pc(Mf,'mpcfit'), pc(Ml,'mpcfit'), Qf.fitErr1, Qf.fitErr96);
fclose(fid); type(fullfile(root, 'results', 'letter_table14.tex'));
fprintf('hindsight averages free/lim %.1f/%.1f\n', pc(Mf,'hindavg'), pc(Ml,'hindavg'));
fprintf('decomposition free/lim: const %.1f/%.1f common %.1f/%.1f fixed %.1f/%.1f blind %.1f/%.1f; congested %.1f%%\n', ...
    pc(Mf,'const'), pc(Ml,'const'), pc(Mf,'common'), pc(Ml,'common'), pc(Mf,'fixed'), pc(Ml,'fixed'), ...
    pc(Mf,'blind'), pc(Ml,'blind'), 100*Ml.congested);

% ---- fleets, histories, sensitivity
ft = {'free', 'lim'}; hd = [60 30 7]; F = nan(6, 4, 2); D = nan(6, 3, 2);
for l = 1:2
    for f = 1:6
        r = ld(sprintf('fleet_%s_60_%d', ft{l}, f)); F(f,:,l) = [pc(r,'prop'), pc(r,'adp'), pc(r,'mpc'), pc(r,'myop')];
        if l == 2                                       % MPC with the fitted forecast
            if f == 4, q = Ql; else, q = ld(sprintf('mpcfit_fleet_%d', f)); end
            F(f,3,l) = pc(q, 'mpcfit');
        end
        for d = 1:3
            r = ld(sprintf('fleet_%s_%d_%d', ft{l}, hd(d), f)); D(f,d,l) = pc(r,'adp') - pc(r,'prop');
        end
    end
    e = F(:,3:4,l) - F(:,1,l);
    fprintf('[fleets %s] ADP-Prop mean by history [60 30 7]: %s, min %.1f, Prop<ADP in %d/18; MPC-Prop %.1f-%.1f, Myop-Prop %.1f-%.1f\n', ...
        ft{l}, mat2str(round(mean(D(:,:,l)),1)), min(min(D(:,:,l))), sum(sum(D(:,:,l) > 0)), ...
        min(e(:,1)), max(e(:,1)), min(e(:,2)), max(e(:,2)));
end
S = nan(12, 3, 2);
for l = 1:2
    for c = 1:12
        r = ld(sprintf('sens_%s_%d', ft{l}, c)); S(c,:,l) = [pc(r,'prop'), pc(r,'adp'), pc(r,'myop')];
    end
    fprintf('[sens %s] Prop %.1f-%.1f, ADP %.1f-%.1f, Myop %.1f-%.1f, Prop best in %d/12\n', ft{l}, ...
        min(S(:,1,l)), max(S(:,1,l)), min(S(:,2,l)), max(S(:,2,l)), min(S(:,3,l)), max(S(:,3,l)), ...
        sum(S(:,1,l) < min(S(:,2:3,l), [], 2)));
end
save(fullfile(root, 'results', 'net14_summary.mat'), 'F', 'D', 'S');

% ---- Fig. 2: six fleets; bars without line limit, diamonds with line 5-6
% limited (Proposed, ADP, MPC with the fitted forecast)
for f = 1:6
    if f == 4, q = Qf; else, q = ld(sprintf('mpcfit_free_fleet_%d', f)); end
    F(f,3,1) = pc(q, 'mpcfit');
end
L = {Mf, ld('lim_4.2'), Ml, ld('lim_2.4')};
Dn = cell2mat(cellfun(@(r) [pc(r,'prop'), pc(r,'adp')], L', 'UniformOutput', false));
Dn(:,3) = [pc(Qf, 'mpcfit'); pc(ld('mpcfit_lim_4.2'), 'mpcfit'); pc(Ql, 'mpcfit'); pc(ld('mpcfit_lim_2.4'), 'mpcfit')];
fn = 'Times New Roman'; fs = 8; yl = [100 150];
toRGB = @(h) sscanf(h(2:end), '%2x%2x%2x')' / 255;
mcol = cellfun(toRGB, {'#0072B2', '#009E73', '#D55E00'}, 'UniformOutput', false);
W = 3.5; H = 1.22; in2n = @(l, b, w, h) [l/W, b/H, w/W, h/H];
f = figure('Units', 'inches', 'Position', [0.5 0.5 W H], 'Color', 'w', 'Visible', 'off');
ax = axes(f, 'Position', in2n(0.40, 0.22, 3.06, 0.78)); hold(ax, 'on');
V0 = F(:,1:3,1); V1 = F(:,1:3,2); n = 6;
b = bar(ax, 1:n, min(V0, yl(2)), 'grouped', 'BarWidth', 0.84, 'EdgeColor', 'none');
for j = 1:3, b(j).FaceColor = mcol{j}; end
for j = 1:3
    xe = b(j).XEndPoints;
    hm = plot(ax, xe, min(V1(:,j), yl(2)), 'd', 'MarkerSize', 3.5, 'MarkerFaceColor', 'w', ...
        'MarkerEdgeColor', [0.1 0.1 0.1], 'LineWidth', 0.6, 'LineStyle', 'none');
    for i = 1:n
        if max(V0(i,j), V1(i,j)) > yl(2)
            text(ax, xe(i), yl(2), sprintf('%.0f', V0(i,j)), 'FontName', fn, 'FontSize', fs-1, ...
                'HorizontalAlignment', 'center', 'VerticalAlignment', 'bottom');
        end
    end
end
set(ax, 'FontName', fn, 'FontSize', fs, 'LabelFontSizeMultiplier', 1, 'TickDir', 'out', 'Box', 'off', ...
    'TickLength', [0.01 0.01], 'XLim', [0.5 n+0.5], 'XTick', 1:n, ...
    'XTickLabel', {'2 close', '2 wide', '4 close', '4 wide', '6 close', '6 wide'}, 'YLim', yl, 'YTick', 100:20:140);
set(ax, 'YGrid', 'on', 'GridColor', [0.85 0.85 0.85], 'GridAlpha', 1);
ylabel(ax, 'Cost (%)');
lg = legend(ax, [b, hm], {'Proposed', 'ADP', 'MPC', 'Line limited'}, 'FontName', fn, 'FontSize', fs, ...
    'Box', 'off', 'Orientation', 'horizontal', 'NumColumns', 4);
lg.ItemTokenSize = [9 6]; lg.Position = in2n(0.40, 1.07, 3.06, 0.13);
exportgraphics(f, fullfile(root, 'Figure', 'fig_robust.pdf'), 'ContentType', 'vector'); close(f);
disp('no limit'); disp(round(V0, 1)); disp('limited'); disp(round(V1, 1)); disp('line limits'); disp(round(Dn, 1));
e0 = V0(:,3) - V0(:,1); e1 = V1(:,3) - V1(:,1);
fprintf('MPC - Prop: no limit %.1f-%.1f, limited %.1f-%.1f; ADP - Prop: no limit %.1f-%.1f, limited %.1f-%.1f\n', ...
    min(e0), max(e0), min(e1), max(e1), min(V0(:,2)-V0(:,1)), max(V0(:,2)-V0(:,1)), min(V1(:,2)-V1(:,1)), max(V1(:,2)-V1(:,1)));
